/** Builds marketing/social/calendar.md (the living schedule) from the post specs. */
import type { PostSpec } from './spec.ts';

const DAYS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];
export const dayName = (date: string) => DAYS[new Date(`${date}T12:00:00Z`).getUTCDay()];

/** Plain text: strips *accents* and line breaks. */
const plain = (s: unknown) => String(s ?? '').replace(/\*/g, '').replace(/\s*\n\s*/g, ' ').trim();

const clip = (s: string, words: number) => {
    const w = s.split(/\s+/);
    return w.length > words ? `${w.slice(0, words).join(' ').replace(/[.,;:!?]+$/, '')}…` : s;
};

/** A one-line label for a post: headline, else quote, question or date label. */
export function headlineOf(spec: PostSpec): string {
    const s = spec.slides[0] ?? {};
    if (s.headline) return plain(s.headline);
    if (s.quote) return `“${clip(plain(s.quote), 6)}” (${plain(s.name)})`;
    if (s.question) return plain(s.question);
    if (s.dateLabel) return `Mini Day: ${plain(s.dateLabel)}`;
    return spec.id;
}

export function buildCalendar(specs: PostSpec[]): string {
    const rows = [...specs]
        .sort((a, b) => a.date.localeCompare(b.date))
        .map((s) => `| ${s.date} | ${dayName(s.date)} | ${s.job} | ${s.template} | ${headlineOf(s)} | ${s.status} |`);
    return [
        '# Christmas 2026 Social Calendar',
        '',
        'Generated by `npm run social:calendar` from `marketing/social/posts/`. Edit the specs, not this file.',
        '',
        '| Date | Day | Job | Template | Post | Status |',
        '|---|---|---|---|---|---|',
        ...rows,
        '',
    ].join('\n');
}
